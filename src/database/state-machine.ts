function glueTask(projectName: string, phase: "schema" | "load"): Record<string, unknown> {
  return {
    Type: "Task",
    Resource: "arn:aws:states:::glue:startJobRun.sync",
    // The ASL state-level field is "Parameters"; the inner "Arguments" carries
    // the Glue StartJobRun arguments.
    Parameters: {
      JobName: `${projectName}-sql-apply`,
      Arguments: { "--phase": phase },
    },
  };
}

/** Step Functions definition that applies the schema and loads Redshift. */
export function warehouseStateMachineDefinition(projectName: string): string {
  const definition = {
    Comment: `Loads ${projectName} into Redshift Serverless. Generated by aws-data-modernizer.`,
    StartAt: "ApplySchema",
    States: {
      ApplySchema: { ...glueTask(projectName, "schema"), Next: "LoadData" },
      LoadData: { ...glueTask(projectName, "load"), End: true },
    },
  };
  return `${JSON.stringify(definition, null, 2)}\n`;
}

/** Step Functions definition that copies HDFS data and loads Apache Iceberg tables. */
export function lakeStateMachineDefinition(projectName: string, hasDataSync: boolean): string {
  const applySchema = { ...glueTask(projectName, "schema"), Next: "LoadData" };
  const loadData = { ...glueTask(projectName, "load"), End: true };
  const definition: Record<string, unknown> = hasDataSync
    ? {
        Comment: `Copies ${projectName} from HDFS and loads Apache Iceberg tables. Generated by aws-data-modernizer.`,
        StartAt: "StartCopy",
        States: {
          StartCopy: {
            Type: "Task",
            Resource: "arn:aws:states:::aws-sdk:datasync:startTaskExecution",
            Parameters: { TaskArn: "${DataSyncTaskArn}" },
            Assign: { executionArn: "{% $states.result.TaskExecutionArn %}" },
            Next: "WaitForCopy",
          },
          WaitForCopy: {
            Type: "Wait",
            Seconds: 60,
            Next: "CheckCopy",
          },
          CheckCopy: {
            Type: "Task",
            Resource: "arn:aws:states:::aws-sdk:datasync:describeTaskExecution",
            Arguments: { TaskExecutionArn: "{% $executionArn %}" },
            Assign: { copyStatus: "{% $states.result.Status %}" },
            Next: "CopyDone",
          },
          CopyDone: {
            Type: "Choice",
            Choices: [
              { Condition: "{% $copyStatus = 'SUCCESS' %}", Next: "ApplySchema" },
              { Condition: "{% $copyStatus = 'ERROR' %}", Next: "CopyFailed" },
            ],
            Default: "WaitForCopy",
          },
          CopyFailed: {
            Type: "Fail",
            Error: "DataSyncCopyFailed",
            Cause: "The DataSync task execution ended with status ERROR.",
          },
          ApplySchema: applySchema,
          LoadData: loadData,
        },
      }
    : {
        Comment: `Copies ${projectName} from HDFS and loads Apache Iceberg tables. Generated by aws-data-modernizer.`,
        StartAt: "ApplySchema",
        States: {
          ApplySchema: applySchema,
          LoadData: loadData,
        },
      };
  return `${JSON.stringify(definition, null, 2)}\n`;
}
