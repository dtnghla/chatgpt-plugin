export type QuoteStyle = "double" | "backtick";

/** Quotes an identifier for the target engine, lower-casing it first. */
export function quoteIdent(name: string, style: QuoteStyle): string {
  const lower = name.toLowerCase();
  if (/^[a-z_][a-z0-9_]*$/.test(lower) && !RESERVED.has(lower)) return lower;
  if (style === "backtick") return `\`${lower.replaceAll("`", "``")}\``;
  return `"${lower.replaceAll('"', '""')}"`;
}

/** Joins a schema and name into a quoted, qualified identifier. */
export function qualified(schema: string, name: string, style: QuoteStyle): string {
  return `${quoteIdent(schema, style)}.${quoteIdent(name, style)}`;
}
