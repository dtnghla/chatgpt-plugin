import { formatBytes, table } from "../convert/report.js";
import type { BundleArtifact } from "./bundle.js";
import { ENGINE_LABELS, TARGET_LABELS } from "./labels.js";
import type { DatabaseAssessment, TableMovement } from "./types.js";

const MAX_TABLE_ROWS = 500;

export interface ReportFile {
  path: string;
  kind: string;
  bytes?: number;
}

export interface DatabaseReportContext {
  projectName: string;
  generatedWith: string;
  assessment: DatabaseAssessment;
  artifacts: BundleArtifact[];
  files: ReportFile[];
  warnings: string[];
  nextSteps: string[];
}

const MOVEMENT_LABELS: Record<TableMovement, string> = {
  dms: "DMS",
  copy: "S3 + COPY",
  datasync: "DataSync",
  s3: "Read in place",
  manual: "Manual",
};

function cappedTable(headers: string[], rows: (string | number | boolean | undefined)[][]): string {
  const body = table(headers, rows.slice(0, MAX_TABLE_ROWS));
  if (rows.length <= MAX_TABLE_ROWS) return body;
  return `${body}\n…and ${rows.length - MAX_TABLE_ROWS} more.`;
}

export function databaseNextSteps(assessment: DatabaseAssessment): string[] {
  const steps: string[] = [];
  const project = assessment.projectName;
  if (assessment.workloadClass === "database") {
    steps.push("Create `dms-vpc-role` if missing.");
    steps.push("Deploy, then fill both secrets.");
    steps.push("Apply `01`–`03` before starting the replication.");
    steps.push("Start DMS, then apply `04` after the full load.");
  } else if (assessment.workloadClass === "warehouse") {
    steps.push("Upload `glue/scripts/` and `sql/`.");
    steps.push("Run the export script and sync it to the staging bucket.");
    steps.push(`Deploy and start \`${project}-warehouse-load\`.`);
  } else {
    steps.push("Deploy a DataSync agent.");
    steps.push("Upload `glue/scripts/` and `sql/`.");
    steps.push(`Deploy and start \`${project}-lake-load\`.`);
  }
  if (assessment.totals.procedural > 0) {
    steps.push(
      `Convert the ${assessment.totals.procedural} procedural objects listed in migration-report.md.`,
    );
  }
  if (assessment.totals.manualColumns > 0) {
    steps.push(
      `Resolve the ${assessment.totals.manualColumns} columns whose types have no automatic mapping.`,
    );
  }
  if (assessment.movement.manualTables > 0) {
    steps.push(`Move the ${assessment.movement.manualTables} tables marked manual separately.`);
  }
  steps.push("Validate row counts and business rules against the source before cut-over.");
  return steps;
}

export function buildDatabaseReport(context: DatabaseReportContext): string {
  const { assessment } = context;
  const lines: string[] = [];
  lines.push(
    `# ${context.projectName}: ${ENGINE_LABELS[assessment.sourceEngine]} to ${TARGET_LABELS[assessment.targetEngine]} modernization report`,
  );
  lines.push("");
  lines.push(
    `Generated by ${context.generatedWith} from the uploaded DDL files only; the generator did not connect to any database or AWS.`,
  );
  lines.push("");
  lines.push(
    `**Readiness:** ${assessment.readiness.score}/100 (${assessment.readiness.level}). ${assessment.readiness.summary}`,
  );
  if (assessment.readiness.blockers.length > 0) {
    lines.push("");
    lines.push("**Blockers:**");
    for (const blocker of assessment.readiness.blockers) lines.push(`- ${blocker}`);
  }
  lines.push("");
  lines.push("## Inventory");
  lines.push("");
  lines.push(
    cappedTable(
      ["File", "Statements", "Size", "SHA-256"],
      assessment.files.map((file) => [
        file.path,
        file.statements,
        formatBytes(file.bytes),
        file.sha256.slice(0, 16),
      ]),
    ),
  );
  lines.push("");
  lines.push("## Object coverage");
  lines.push("");
  lines.push(
    cappedTable(
      ["Object", "Count", "Automatic", "Partial", "Manual", "Conversion"],
      assessment.objectCoverage.map((coverage) => [
        coverage.kind,
        coverage.count,
        coverage.automatic,
        coverage.partial,
        coverage.manual,
        coverage.conversion,
      ]),
    ),
  );
  lines.push("");
  lines.push("## Column type mapping");
  lines.push("");
  lines.push(
    cappedTable(
      ["Source type", "Columns", "Status", "Target type", "Notes"],
      assessment.typeCoverage.map((coverage) => [
        coverage.sourceType,
        coverage.count,
        coverage.status,
        coverage.targetType,
        coverage.caveat ?? "",
      ]),
    ),
  );
  lines.push("");
  lines.push("## Items needing attention");
  lines.push("");
  if (assessment.attention.length === 0) {
    lines.push("No columns, views or objects need manual work.");
  } else {
    lines.push(
      cappedTable(
        ["Kind", "Name", "Location", "Status", "Reason"],
        assessment.attention.map((item) => [
          item.kind,
          item.name,
          `${item.file}:${item.line}`,
          item.status,
          item.reason,
        ]),
      ),
    );
  }
  lines.push("");
  lines.push("## Procedural objects");
  lines.push("");
  if (assessment.procedural.length === 0) {
    lines.push("No procedural code was found.");
  } else {
    lines.push(
      cappedTable(
        ["Object", "Kind", "Lines", "Complexity", "Features"],
        assessment.procedural.map((proc) => [
          `${proc.schema}.${proc.name}`,
          proc.kind,
          proc.lines,
          proc.complexity,
          proc.features.join(", "),
        ]),
      ),
    );
  }
  lines.push("");
  lines.push("## Tables and data movement");
  lines.push("");
  lines.push(
    cappedTable(
      ["Table", "Columns", "Primary key", "Movement", "Status", "Location"],
      assessment.tables.map((row) => [
        `${row.schema}.${row.name}`,
        row.columns,
        row.primaryKey ? "yes" : "no",
        MOVEMENT_LABELS[row.movement],
        row.status,
        row.location ?? "",
      ]),
    ),
  );
  lines.push("");
  lines.push("## Data movement");
  lines.push("");
  lines.push(assessment.movement.summary);
  lines.push("");
  lines.push("## Generated artifacts");
  lines.push("");
  lines.push(
    cappedTable(
      ["Path", "Kind", "Purpose"],
      context.artifacts.map((artifact) => [artifact.path, artifact.kind, artifact.description]),
    ),
  );
  lines.push("");
  lines.push("## Risks");
  lines.push("");
  if (assessment.risks.length === 0) {
    lines.push("No risks were recorded.");
  } else {
    lines.push(
      cappedTable(
        ["Severity", "Code", "Message", "File"],
        assessment.risks.map((risk) => [risk.severity, risk.code, risk.message, risk.file ?? ""]),
      ),
    );
  }
  if (context.warnings.length > 0) {
    lines.push("");
    lines.push("## Generation warnings");
    lines.push("");
    for (const warning of context.warnings) lines.push(`- ${warning}`);
  }
  lines.push("");
  lines.push("## Open questions");
  lines.push("");
  if (assessment.questions.length === 0) {
    lines.push("No open questions were recorded.");
  } else {
    for (const question of assessment.questions) lines.push(`- ${question}`);
  }
  lines.push("");
  lines.push("## Next steps");
  lines.push("");
  for (const step of context.nextSteps) lines.push(`- ${step}`);
  lines.push("");
  lines.push(
    "The generated bundle is a starting point, not a proof of equivalence. Validate row counts, data types and business rules against the source system before cut-over.",
  );
  lines.push("");
  return lines.join("\n");
}

export function buildDatabaseReadme(context: DatabaseReportContext): string {
  const { assessment } = context;
  const workloadClass = assessment.workloadClass;
  const projectName = context.projectName;
  const lines: string[] = [];
  lines.push(`# ${projectName} AWS modernization bundle`);
  lines.push("");
  lines.push(
    `Generated by ${context.generatedWith} from ${ENGINE_LABELS[assessment.sourceEngine]} DDL files.`,
  );
  lines.push("");
  lines.push(
    "This bundle is deployable infrastructure-as-code, but it is generated advice rather than a validated migration. The generator never connected to a database or AWS and holds no credentials.",
  );
  lines.push("");
  lines.push("## Contents");
  lines.push("");
  lines.push("```text");
  for (const file of context.files) {
    lines.push(file.bytes === undefined ? file.path : `${file.path}  (${formatBytes(file.bytes)})`);
  }
  lines.push("```");
  lines.push("");
  lines.push("## Before you deploy");
  lines.push("");
  if (workloadClass === "database") {
    lines.push(
      "1. Read `migration-report.md`, especially the readiness block, risks and open questions.",
    );
    lines.push(
      "2. Create the `dms-vpc-role` IAM role if it does not exist yet, so DMS can manage subnets:",
    );
    lines.push("");
    lines.push("```bash");
    lines.push(
      'aws iam create-role --role-name dms-vpc-role --assume-role-policy-document \'{"Version":"2012-10-17","Statement":[{"Effect":"Allow","Principal":{"Service":"dms.amazonaws.com"},"Action":"sts:AssumeRole"}]}\'',
    );
    lines.push(
      "aws iam attach-role-policy --role-name dms-vpc-role --policy-arn arn:aws:iam::aws:policy/service-role/AmazonDMSVPCManagementRole",
    );
    lines.push("```");
    lines.push("");
    const cdcNote =
      assessment.sourceEngine === "oracle"
        ? "Oracle: enable ARCHIVELOG mode and supplemental logging."
        : assessment.sourceEngine === "sqlserver"
          ? "SQL Server: enable MS-CDC or MS-Replication."
          : assessment.sourceEngine === "mysql"
            ? "MySQL: set `binlog_format=ROW`."
            : "PostgreSQL: enable logical replication.";
    lines.push(`3. Enable CDC on the source: ${cdcNote}`);
  } else if (workloadClass === "warehouse") {
    lines.push(
      "1. Read `migration-report.md`, especially the readiness block, risks and open questions.",
    );
    lines.push(
      "2. Provision a host with `tbuild` (Teradata) or `nzsql` (Netezza) access that can reach the source warehouse and upload to the S3 staging bucket.",
    );
  } else {
    lines.push(
      "1. Read `migration-report.md`, especially the readiness block, risks and open questions.",
    );
    lines.push("2. Deploy a DataSync agent that can reach the HDFS NameNode.");
  }
  lines.push("");
  lines.push("## Deploy with the AWS CLI");
  lines.push("");
  lines.push("```bash");
  lines.push('AWS_REGION="us-east-1"');
  lines.push(`STACK_NAME="${projectName}"`);
  const overrides =
    workloadClass === "database"
      ? [
          '"SubnetIds=subnet-aaaaaaaa,subnet-bbbbbbbb"',
          '"SecurityGroupIds=sg-00000000"',
          ...(assessment.sourceEngine === "mysql" ? [] : ['"SourceDatabaseName=ORCL"']),
        ]
      : workloadClass === "warehouse"
        ? [
            '"ScriptsBucket=my-scripts-bucket"',
            '"StagingBucket=my-staging-bucket"',
            '"SubnetIds=subnet-aaaaaaaa,subnet-bbbbbbbb"',
            '"SecurityGroupIds=sg-00000000"',
          ]
        : [
            '"ScriptsBucket=my-scripts-bucket"',
            '"LakeBucket=my-lake-bucket"',
            ...(assessment.tables.some((row) => row.movement === "datasync")
              ? [
                  '"DataSyncAgentArn=arn:aws:datasync:us-east-1:123456789012:agent/agent-example"',
                  '"HdfsNameNodeHost=namenode.example.com"',
                  '"HdfsNameNodePort=8020"',
                  '"HdfsUser=hdfs"',
                ]
              : []),
          ];
  lines.push("aws cloudformation deploy \\");
  lines.push('  --region "$AWS_REGION" \\');
  lines.push('  --stack-name "$STACK_NAME" \\');
  lines.push("  --template-file cloudformation/data-modernization.yaml \\");
  lines.push("  --capabilities CAPABILITY_IAM \\");
  lines.push(`  --parameter-overrides ${overrides.join(" ")}`);
  lines.push("```");
  lines.push("");
  if (workloadClass === "database") {
    lines.push("Fill both secrets after the stack is created:");
    lines.push("");
    lines.push("```bash");
    lines.push(
      `aws secretsmanager put-secret-value --secret-id "${projectName}/source-database" --secret-string '{"username":"<USER>","password":"<PASSWORD>","host":"<HOST>","port":"<PORT>"}'`,
    );
    lines.push(
      `aws secretsmanager put-secret-value --secret-id "${projectName}/target-database" --secret-string '{"username":"<USER>","password":"<PASSWORD>"}'`,
    );
    lines.push("```");
    lines.push("");
    lines.push("The Aurora master password comes from the `MasterUserSecretArn` stack output.");
    lines.push("");
    lines.push("Apply the target schema before starting the replication:");
    lines.push("");
    if (assessment.targetEngine === "aurora-postgresql") {
      lines.push("```bash");
      lines.push(
        'psql "host=$AURORA_ENDPOINT dbname=modernized user=dbadmin sslmode=require" -f sql/target/01-schemas.sql -f sql/target/02-tables.sql -f sql/target/03-views.sql',
      );
      lines.push("```");
    } else {
      lines.push("```bash");
      lines.push(
        'mysql --host="$AURORA_ENDPOINT" --user=dbadmin --password --ssl-mode=REQUIRED < sql/target/01-schemas.sql',
      );
      lines.push(
        'mysql --host="$AURORA_ENDPOINT" --user=dbadmin --password --ssl-mode=REQUIRED < sql/target/02-tables.sql',
      );
      lines.push(
        'mysql --host="$AURORA_ENDPOINT" --user=dbadmin --password --ssl-mode=REQUIRED < sql/target/03-views.sql',
      );
      lines.push("```");
    }
    lines.push("");
    lines.push("Start the replication:");
    lines.push("");
    lines.push("```bash");
    lines.push(
      'aws dms start-replication --replication-config-arn "$REPLICATION_CONFIG_ARN" --start-replication-type start-replication',
    );
    lines.push("```");
    lines.push("");
    lines.push("After the full load finishes, apply `sql/target/04-constraints-indexes.sql`.");
    lines.push("");
  } else {
    lines.push("Upload the scripts and SQL, then start the state machine:");
    lines.push("");
    lines.push("```bash");
    lines.push('aws s3 cp --recursive glue/scripts/ "s3://$SCRIPTS_BUCKET/glue/scripts/"');
    lines.push('aws s3 cp --recursive sql/ "s3://$SCRIPTS_BUCKET/sql/"');
    if (workloadClass === "warehouse") {
      lines.push("");
      lines.push("# Run the export script on the warehouse host, then sync the output:");
      lines.push('aws s3 sync "$EXPORT_DIR" "s3://$STAGING_BUCKET/"');
    }
    lines.push("");
    lines.push(
      "aws stepfunctions start-execution --state-machine-arn \"<StateMachineArn output>\" --input '{}'",
    );
    lines.push("```");
    lines.push("");
  }
  lines.push("## Limitations");
  lines.push("");
  lines.push(
    "- Procedural code (procedures, functions, triggers, packages, macros and BTEQ scripts) is inventoried, not converted.",
  );
  lines.push(
    "- Views are rewritten with rules and must be reviewed before they run against the target.",
  );
  if (workloadClass === "database") {
    lines.push(
      "- DMS CDC needs a primary or unique key on every table; full-load-only tables receive no ongoing changes.",
    );
    lines.push(
      "- DMS limited LOB mode truncates LOB values over 32 KB; raise `LobMaxSize` in `dms/replication-settings.json` or switch to full LOB mode when needed.",
    );
  }
  if (workloadClass === "warehouse") {
    lines.push(
      "- The generated export scripts write pipe-delimited files; tables with binary or large-object columns are marked manual in `migration-report.md`.",
    );
    lines.push(
      "- Redshift distribution and sort keys are derived from the source; verify them against your query patterns.",
    );
  }
  if (workloadClass === "lake") {
    lines.push(
      "- Hive ACID (transactional) tables must be major-compacted and exported manually; Athena cannot read Hive ACID delta files.",
    );
    lines.push(
      "- Apache Iceberg tables are created without `IF NOT EXISTS`; re-running the load phase after a failed insert can error and is skipped by the apply plan.",
    );
  }
  lines.push("");
  return lines.join("\n");
}
