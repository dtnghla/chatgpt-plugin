import { decideTableMovement } from "./assessment.js";
import type { QuoteStyle } from "./names.js";
import { qualified, quoteIdent } from "./names.js";
import { rewriteViewSql, translateDefault } from "./sql-rewrite.js";
import { mapColumnType } from "./type-mapping.js";
import type {
  ColumnDef,
  DatabaseProject,
  IndexDef,
  SequenceDef,
  SourceEngine,
  TableDef,
  ViewDef,
} from "./types.js";

export interface DataSyncScope {
  /** HDFS subdirectory the DataSync task copies. */
  root: string;
  /** SIMPLE_PATTERN include filter, omitted when it would exceed 4,096 characters. */
  includeFilter?: string;
}

export interface GeneratedTargetDdl {
  files: Map<string, string>;
  warnings: string[];
  datasync?: DataSyncScope;
  /** Distinct S3 bucket names of tables that stay on S3. */
  externalS3Buckets: string[];
}

const LAKE_BUCKET = "${LakeBucket}";
const STAGING_BUCKET = "${StagingBucket}";
const MAX_INCLUDE_FILTER = 4_096;

interface SourceObject {
  file: string;
  line: number;
  sql: string;
}

function sourceComment(file: string, line: number): string {
  return `-- Source: ${file}:${line}`;
}

function joinBlocks(blocks: string[]): string {
  return blocks.length > 0 ? `${blocks.join("\n\n")}\n` : "";
}

function schemaTable(table: TableDef, style: QuoteStyle): string {
  return qualified(table.schema, table.name, style);
}

function isBareIdentifier(text: string): boolean {
  return /^[A-Za-z_][A-Za-z0-9_]*$/.test(text);
}

function columnList(columns: string[], style: QuoteStyle): string {
  return columns
    .map((column) => (isBareIdentifier(column) ? quoteIdent(column, style) : column))
    .join(", ");
}

function sequenceStatement(sequence: SequenceDef): string {
  const start = sequence.start !== undefined ? ` START WITH ${sequence.start}` : "";
  const increment = sequence.increment !== undefined ? ` INCREMENT BY ${sequence.increment}` : "";
  return `CREATE SEQUENCE IF NOT EXISTS ${qualified(sequence.schema, sequence.name, "double")}${start}${increment};`;
}

/** Identity columns, in declaration order. */
function identityColumns(table: TableDef): ColumnDef[] {
  return table.columns.filter((column) => column.identity && column.computed === undefined);
}

function unqualifiedTable(index: IndexDef): { schema: string; name: string } {
  const dot = index.table.indexOf(".");
  return dot >= 0
    ? { schema: index.table.slice(0, dot), name: index.table.slice(dot + 1) }
    : { schema: index.schema, name: index.table };
}

function sourceOrdered<T extends { file: string; line: number }>(items: T[]): T[] {
  return [...items].sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line);
}

function statementBlock(object: SourceObject): string {
  return [sourceComment(object.file, object.line), object.sql].join("\n");
}

function viewToStatement(view: ViewDef): SourceObject {
  return { file: view.file, line: view.line, sql: view.sql };
}

function indexToStatement(index: IndexDef): SourceObject {
  return { file: index.file, line: index.line, sql: index.sql };
}

// --- Aurora PostgreSQL elements (also used by the Redshift DDL) -----------------

function columnElement(
  engine: SourceEngine,
  column: ColumnDef,
  mappedTargetType: string,
  redshift: boolean,
): string {
  const identity = redshift
    ? " GENERATED BY DEFAULT AS IDENTITY(1,1)"
    : " GENERATED BY DEFAULT AS IDENTITY";
  let element = `    ${quoteIdent(column.name, "double")} ${mappedTargetType}`;
  if (column.identity) element += identity;
  if (!column.nullable) element += " NOT NULL";
  if (column.defaultExpression !== undefined) {
    const translated = translateDefault(engine, column.defaultExpression, mappedTargetType);
    if (translated !== undefined) element += ` DEFAULT ${translated}`;
  }
  return element;
}

function auroraPostgresqlTableStatement(engine: SourceEngine, table: TableDef): string {
  const elements: string[] = [];
  for (const column of table.columns) {
    if (column.computed !== undefined) continue;
    elements.push(columnElement(engine, column, mapColumnType(engine, column).targetType, false));
  }
  if (table.primaryKey.length > 0) {
    elements.push(
      `    CONSTRAINT ${quoteIdent(`${table.name}_pkey`, "double")} PRIMARY KEY (${columnList(table.primaryKey, "double")})`,
    );
  }
  table.uniqueKeys.forEach((columns, i) => {
    elements.push(
      `    CONSTRAINT ${quoteIdent(`${table.name}_uk${i + 1}`, "double")} UNIQUE (${columnList(columns, "double")})`,
    );
  });
  return `CREATE TABLE IF NOT EXISTS ${schemaTable(table, "double")} (\n${elements.join(",\n")}\n);`;
}

function redshiftTableStatement(engine: SourceEngine, table: TableDef): string {
  const elements: string[] = [];
  for (const column of table.columns) {
    if (column.computed !== undefined) continue;
    elements.push(columnElement(engine, column, mapColumnType(engine, column).targetType, true));
  }
  if (table.primaryKey.length > 0) {
    elements.push(`    PRIMARY KEY (${columnList(table.primaryKey, "double")})`);
  }
  let distribution: string;
  if (table.distribution?.kind === "key") {
    distribution =
      table.distribution.columns.length === 1
        ? `DISTSTYLE KEY DISTKEY (${columnList(table.distribution.columns, "double")})`
        : "DISTSTYLE AUTO";
  } else if (table.distribution?.kind === "random") {
    distribution = "DISTSTYLE EVEN";
  } else {
    distribution = "DISTSTYLE AUTO";
  }
  const sortKey =
    table.sortColumns.length > 0 ? `\nSORTKEY (${columnList(table.sortColumns, "double")})` : "";
  return `CREATE TABLE IF NOT EXISTS ${schemaTable(table, "double")} (\n${elements.join(",\n")}\n)\n${distribution}${sortKey};`;
}

function manualColumnComments(engine: SourceEngine, table: TableDef): string[] {
  const comments: string[] = [];
  for (const column of table.columns) {
    const mapped = mapColumnType(engine, column);
    if (column.computed !== undefined) {
      comments.push(
        `-- MANUAL: computed column ${column.name.toLowerCase()} AS ${column.computed} is not created.`,
      );
      continue;
    }
    if (mapped.status === "manual") {
      comments.push(
        `-- MANUAL: column ${column.name.toLowerCase()} (${column.sourceType}) generated as ${mapped.targetType}: ${mapped.caveat}`,
      );
    }
  }
  return comments;
}

function viewBlock(
  engine: SourceEngine,
  view: ViewDef,
  quoteStyle: QuoteStyle,
  allowMaterialized: boolean,
): string {
  const rewrite = rewriteViewSql(engine, view.body);
  const lines = [sourceComment(view.file, view.line)];
  if (rewrite.status === "manual") {
    lines.push(`-- MANUAL: uses ${rewrite.manualFeatures.join(", ")}; rewrite before running.`);
    lines.push(
      view.sql
        .split("\n")
        .map((line) => `-- ${line}`)
        .join("\n"),
    );
    return lines.join("\n");
  }
  if (allowMaterialized && view.materialized) {
    lines.push(
      `CREATE MATERIALIZED VIEW IF NOT EXISTS ${qualified(view.schema, view.name, quoteStyle)} AS\n${rewrite.sql}\nWITH NO DATA;`,
    );
    return lines.join("\n");
  }
  lines.push(`-- REVIEW: rewritten with rules: ${rewrite.applied.join(", ") || "none"}`);
  lines.push(
    `CREATE OR REPLACE VIEW ${qualified(view.schema, view.name, quoteStyle)} AS\n${rewrite.sql};`,
  );
  return lines.join("\n");
}

function setvalStatements(project: DatabaseProject): string[] {
  const statements: string[] = [];
  for (const table of sourceOrdered(project.tables)) {
    for (const column of identityColumns(table)) {
      const qualifiedName = `${table.schema.toLowerCase()}.${table.name.toLowerCase()}`;
      const escaped = qualifiedName.replaceAll("'", "''");
      const columnName = column.name.toLowerCase();
      statements.push(
        `SELECT setval(pg_get_serial_sequence('${escaped}', '${columnName}'), COALESCE(MAX(${quoteIdent(columnName, "double")}), 0) + 1, false) FROM ${schemaTable(table, "double")};`,
      );
    }
  }
  return statements;
}

// --- Aurora PostgreSQL from oracle or sqlserver ---------------------------------

function auroraPostgresqlIndexBlocks(project: DatabaseProject): string[] {
  const blocks: string[] = [];
  for (const index of sourceOrdered(project.indexes)) {
    const lines: string[] = [sourceComment(index.file, index.line)];
    if (index.bitmap) {
      lines.push("-- REVIEW: bitmap index recreated as a B-tree index.");
    }
    if (index.expression) {
      lines.push("-- REVIEW: expression index copied from the source; check the functions.");
    }
    const target = unqualifiedTable(index);
    const unique = index.unique ? "UNIQUE " : "";
    lines.push(
      `CREATE ${unique}INDEX IF NOT EXISTS ${quoteIdent(index.name, "double")} ON ${qualified(target.schema, target.name, "double")} (${columnList(index.columns, "double")});`,
    );
    blocks.push(lines.join("\n"));
  }
  return blocks;
}

function generateAuroraPostgresqlFromSources(project: DatabaseProject): GeneratedTargetDdl {
  const engine = project.engine;
  const files = new Map<string, string>();
  files.set(
    "sql/target/01-schemas.sql",
    joinBlocks(
      project.schemas.map(
        (schema) => `CREATE SCHEMA IF NOT EXISTS ${quoteIdent(schema, "double")};`,
      ),
    ),
  );

  const tableBlocks: string[] = [];
  for (const sequence of sourceOrdered(project.sequences)) {
    tableBlocks.push(
      [sourceComment(sequence.file, sequence.line), sequenceStatement(sequence)].join("\n"),
    );
  }
  for (const table of sourceOrdered(project.tables)) {
    const lines: string[] = [sourceComment(table.file, table.line)];
    if (table.createdFromQuery) {
      lines.push(
        `-- MANUAL: ${schemaTable(table, "double")} is created from a query in the source; define its columns manually.`,
      );
      tableBlocks.push(lines.join("\n"));
      continue;
    }
    lines.push(...manualColumnComments(engine, table));
    if (table.partitioning !== undefined) {
      lines.push(`-- REVIEW: partitioned in the source (${table.partitioning}).`);
    }
    lines.push(auroraPostgresqlTableStatement(engine, table));
    tableBlocks.push(lines.join("\n"));
  }
  files.set("sql/target/02-tables.sql", joinBlocks(tableBlocks));

  files.set(
    "sql/target/03-views.sql",
    joinBlocks(sourceOrdered(project.views).map((view) => viewBlock(engine, view, "double", true))),
  );

  const constraintBlocks: string[] = [];
  for (const table of sourceOrdered(project.tables)) {
    if (table.foreignKeys.length === 0) continue;
    const lines = [sourceComment(table.file, table.line)];
    table.foreignKeys.forEach((foreignKey, i) => {
      lines.push(
        `ALTER TABLE ${schemaTable(table, "double")} ADD CONSTRAINT ${quoteIdent(`${table.name}_fk${i + 1}`, "double")} FOREIGN KEY (${columnList(foreignKey.columns, "double")}) REFERENCES ${qualified(foreignKey.referencedSchema, foreignKey.referencedTable, "double")} (${columnList(foreignKey.referencedColumns, "double")});`,
      );
    });
    constraintBlocks.push(lines.join("\n"));
  }
  constraintBlocks.push(...auroraPostgresqlIndexBlocks(project));
  const setvals = setvalStatements(project);
  if (setvals.length > 0) constraintBlocks.push(setvals.join("\n"));
  files.set("sql/target/04-constraints-indexes.sql", joinBlocks(constraintBlocks));

  return { files, warnings: [], externalS3Buckets: [] };
}

// --- Aurora PostgreSQL from postgresql -------------------------------------------

function generatePostgresqlHomogeneous(project: DatabaseProject): GeneratedTargetDdl {
  const files = new Map<string, string>();
  files.set(
    "sql/target/01-schemas.sql",
    joinBlocks(
      project.schemas.map(
        (schema) => `CREATE SCHEMA IF NOT EXISTS ${quoteIdent(schema, "double")};`,
      ),
    ),
  );

  const objects: SourceObject[] = [
    ...project.sequences.map((sequence) => ({
      file: sequence.file,
      line: sequence.line,
      sql: sequence.sql,
    })),
    ...project.tables.map((table) => ({ file: table.file, line: table.line, sql: table.sql })),
  ];
  files.set(
    "sql/target/02-tables.sql",
    joinBlocks(sourceOrdered(objects).map((object) => statementBlock(object))),
  );

  files.set(
    "sql/target/03-views.sql",
    joinBlocks(sourceOrdered(project.views).map((view) => statementBlock(viewToStatement(view)))),
  );

  const constraintBlocks: string[] = project.constraintStatements.map((statement) =>
    statementBlock(statement),
  );
  constraintBlocks.push(
    ...sourceOrdered(project.indexes).map((index) => statementBlock(indexToStatement(index))),
  );
  const setvals = setvalStatements(project);
  if (setvals.length > 0) constraintBlocks.push(setvals.join("\n"));
  files.set("sql/target/04-constraints-indexes.sql", joinBlocks(constraintBlocks));

  return { files, warnings: [], externalS3Buckets: [] };
}

// --- Aurora MySQL from mysql -------------------------------------------------------

function generateAuroraMysql(project: DatabaseProject): GeneratedTargetDdl {
  const files = new Map<string, string>();
  files.set(
    "sql/target/01-schemas.sql",
    joinBlocks(
      project.schemas.map(
        (schema) => `CREATE DATABASE IF NOT EXISTS \`${schema.replaceAll("`", "``")}\`;`,
      ),
    ),
  );

  const tableBlocks: string[] = [];
  for (const sequence of sourceOrdered(project.sequences)) {
    tableBlocks.push(
      [
        sourceComment(sequence.file, sequence.line),
        "-- MANUAL: Aurora MySQL has no sequences; use AUTO_INCREMENT.",
        sequence.sql
          .split("\n")
          .map((line) => `-- ${line}`)
          .join("\n"),
      ].join("\n"),
    );
  }
  for (const table of sourceOrdered(project.tables)) {
    tableBlocks.push(
      [
        sourceComment(table.file, table.line),
        table.sql.replace(/ENGINE\s*=\s*(?!InnoDB\b)\w+/gi, "ENGINE=InnoDB"),
      ].join("\n"),
    );
  }
  files.set("sql/target/02-tables.sql", joinBlocks(tableBlocks));

  files.set(
    "sql/target/03-views.sql",
    joinBlocks(sourceOrdered(project.views).map((view) => statementBlock(viewToStatement(view)))),
  );

  const STANDALONE_INDEX =
    /^CREATE\s+(UNIQUE\s+)?((CLUSTERED|NONCLUSTERED|BITMAP|FULLTEXT|SPATIAL)\s+)*INDEX\b/i;
  const constraintBlocks: string[] = [];
  for (const index of sourceOrdered(project.indexes)) {
    if (!STANDALONE_INDEX.test(index.sql)) continue;
    constraintBlocks.push(statementBlock(indexToStatement(index)));
  }
  for (const statement of project.constraintStatements) {
    constraintBlocks.push(statementBlock(statement));
  }
  files.set("sql/target/04-constraints-indexes.sql", joinBlocks(constraintBlocks));

  return { files, warnings: [], externalS3Buckets: [] };
}

// --- Redshift from teradata or netezza ---------------------------------------------

function generateRedshift(project: DatabaseProject): GeneratedTargetDdl {
  const engine = project.engine;
  const files = new Map<string, string>();
  files.set(
    "sql/target/01-schemas.sql",
    joinBlocks(
      project.schemas.map(
        (schema) => `CREATE SCHEMA IF NOT EXISTS ${quoteIdent(schema, "double")};`,
      ),
    ),
  );

  const tableBlocks: string[] = [];
  const copyBlocks: string[] = [];
  for (const table of sourceOrdered(project.tables)) {
    const decision = decideTableMovement(project, table);
    if (decision.movement === "copy") {
      copyBlocks.push(
        [
          `-- ${schemaTable(table, "double")} from ${table.file}:${table.line}`,
          `COPY ${schemaTable(table, "double")} FROM 's3://${STAGING_BUCKET}/${table.schema.toLowerCase()}/${table.name.toLowerCase()}/' IAM_ROLE default FORMAT AS CSV DELIMITER '|' QUOTE AS '"' EMPTYASNULL DATEFORMAT 'auto' TIMEFORMAT 'auto' ACCEPTINVCHARS${identityColumns(table).length > 0 ? " EXPLICIT_IDS" : ""};`,
        ].join("\n"),
      );
    }
    const lines: string[] = [sourceComment(table.file, table.line)];
    if (table.createdFromQuery) {
      lines.push(
        `-- MANUAL: ${schemaTable(table, "double")} is created from a query in the source; define its columns manually.`,
      );
      tableBlocks.push(lines.join("\n"));
      continue;
    }
    lines.push(...manualColumnComments(engine, table));
    if (table.distribution?.kind === "key" && table.distribution.columns.length > 1) {
      lines.push(
        `-- REVIEW: multi-column distribution (${columnList(table.distribution.columns, "double")}) mapped to DISTSTYLE AUTO.`,
      );
    }
    if (engine === "teradata" && table.partitioning !== undefined && table.sortColumns.length > 0) {
      lines.push("-- REVIEW: sort key derived from the source partitioning.");
    }
    lines.push(redshiftTableStatement(engine, table));
    tableBlocks.push(lines.join("\n"));
  }
  files.set("sql/target/02-tables.sql", joinBlocks(tableBlocks));

  files.set(
    "sql/target/03-views.sql",
    joinBlocks(
      sourceOrdered(project.views).map((view) => viewBlock(engine, view, "double", false)),
    ),
  );

  files.set("sql/load/copy.sql", joinBlocks(copyBlocks));

  return { files, warnings: [], externalS3Buckets: [] };
}

// --- Athena Iceberg from hive -------------------------------------------------------

function athenaIdent(name: string): string {
  return quoteIdent(name, "backtick");
}

function sqlIdent(name: string): string {
  return quoteIdent(name, "double");
}

function computeDataSyncScope(paths: string[]): { root: string; relativePaths: string[] } {
  const parents = paths.map((path) => {
    const segments = path.split("/");
    segments.pop();
    const joined = segments.join("/");
    return joined === "" ? "/" : joined;
  });
  const segmentLists = parents.map((parent) => parent.split("/").filter((s) => s !== ""));
  let common: string[] = [];
  if (segmentLists.length > 0 && segmentLists[0]) {
    common = [...segmentLists[0]];
    for (const segments of segmentLists.slice(1)) {
      const next: string[] = [];
      for (let i = 0; i < common.length && i < segments.length; i++) {
        const mine = common[i];
        const theirs = segments[i];
        if (mine !== undefined && mine === theirs) next.push(mine);
        else break;
      }
      common = next;
    }
  }
  const root = common.length === 0 ? "/" : `/${common.join("/")}`;
  const relativePaths = paths.map((path) =>
    root === "/" ? path.slice(1) : path.slice(root.length + 1),
  );
  return { root, relativePaths };
}

function generateAthenaIceberg(project: DatabaseProject): GeneratedTargetDdl {
  const warnings: string[] = [];
  const files = new Map<string, string>();

  const databases = project.schemas
    .map((schema) => schema.toLowerCase())
    .sort((a, b) => a.localeCompare(b));
  files.set(
    "sql/target/01-databases.sql",
    joinBlocks(
      databases.flatMap((db) => [
        `CREATE DATABASE IF NOT EXISTS ${athenaIdent(`${db}_raw`)};`,
        `CREATE DATABASE IF NOT EXISTS ${athenaIdent(db)};`,
      ]),
    ),
  );

  const tableDecisions = project.tables.map((table) => ({
    table,
    decision: decideTableMovement(project, table),
  }));
  const datasyncPaths = tableDecisions
    .filter((entry) => entry.decision.movement === "datasync")
    .map((entry) => entry.decision.hdfsPath ?? "/");
  const { root, relativePaths } = computeDataSyncScope(datasyncPaths);
  let includeFilter = relativePaths.map((relative) => `/${relative}`).join("|");
  if (includeFilter.length > MAX_INCLUDE_FILTER) {
    warnings.push(
      `DataSync include filter omitted because it exceeds 4,096 characters; the task copies the whole ${root} subtree.`,
    );
    includeFilter = "";
  }

  const externalS3Buckets = new Set<string>();
  let relativeIndex = 0;
  const rawBlocks: string[] = [];
  const icebergBlocks: string[] = [];
  const loadLines: string[] = [];
  for (const { table, decision } of tableDecisions) {
    if (decision.movement !== "datasync" && decision.movement !== "s3") continue;
    const db = table.schema.toLowerCase();
    const name = table.name.toLowerCase();
    let rawLocation: string | undefined;
    if (decision.movement === "datasync") {
      const relative = relativePaths[relativeIndex] ?? "";
      relativeIndex++;
      rawLocation = `s3://${LAKE_BUCKET}/raw/${relative}/`;
    } else if (decision.location) {
      rawLocation = decision.location;
      const bucket = decision.location.slice("s3://".length).split("/")[0] ?? "";
      if (bucket !== "") externalS3Buckets.add(bucket);
    }
    if (rawLocation === undefined) continue;

    // Raw external table over the copied files.
    const rawLines: string[] = [
      `CREATE EXTERNAL TABLE IF NOT EXISTS ${athenaIdent(`${db}_raw`)}.${athenaIdent(name)} (`,
    ];
    if (table.columns.length > 0) {
      rawLines.push(
        table.columns
          .map(
            (column) =>
              `  ${athenaIdent(column.name.toLowerCase())} ${column.sourceType.toLowerCase()}`,
          )
          .join(",\n"),
      );
    }
    rawLines.push(")");
    if (table.partitionColumns.length > 0) {
      rawLines.push(
        `PARTITIONED BY (${table.partitionColumns
          .map(
            (column) =>
              `${athenaIdent(column.name.toLowerCase())} ${column.sourceType.toLowerCase()}`,
          )
          .join(", ")})`,
      );
    }
    if (table.hive?.rowFormat) rawLines.push(table.hive.rowFormat);
    if (table.hive?.storedAs) rawLines.push(table.hive.storedAs);
    rawLines.push(`LOCATION '${rawLocation}'`);
    const properties = Object.entries(table.hive?.tblProperties ?? {}).filter(
      ([key]) => key.toLowerCase() !== "transactional",
    );
    if (properties.length > 0) {
      rawLines.push(
        `TBLPROPERTIES (${properties.map(([key, value]) => `'${key}'='${value}'`).join(", ")})`,
      );
    }
    rawBlocks.push(`${rawLines.join("\n")};`);

    // Iceberg table: regular columns first, partition columns last.
    const charBase = (sourceType: string): boolean =>
      (sourceType.split(/[\s(]/)[0] ?? "").toUpperCase() === "CHAR";
    const regular = table.columns.map((column) => ({
      name: column.name.toLowerCase(),
      type: mapColumnType(project.engine, column).targetType,
      isChar: charBase(column.sourceType),
    }));
    const partitionColumns = table.partitionColumns.map((column) => ({
      name: column.name.toLowerCase(),
      type: mapColumnType(project.engine, column).targetType,
      isChar: charBase(column.sourceType),
    }));
    const icebergLines: string[] = [`CREATE TABLE ${athenaIdent(db)}.${athenaIdent(name)} (`];
    if (regular.length + partitionColumns.length > 0) {
      icebergLines.push(
        [...regular, ...partitionColumns]
          .map((column) => `  ${athenaIdent(column.name)} ${column.type}`)
          .join(",\n"),
      );
    }
    icebergLines.push(")");
    const partitions = [
      ...partitionColumns.map((column) => athenaIdent(column.name)),
      ...(table.buckets
        ? table.buckets.columns.map(
            (column) =>
              `bucket(${table.buckets?.count ?? 8}, ${athenaIdent(column.toLowerCase())})`,
          )
        : []),
    ];
    if (partitions.length > 0) {
      icebergLines.push(`PARTITIONED BY (${partitions.join(", ")})`);
    }
    icebergLines.push(`LOCATION 's3://${LAKE_BUCKET}/iceberg/${db}/${name}/'`);
    icebergLines.push("TBLPROPERTIES ('table_type' = 'ICEBERG', 'format' = 'parquet');");
    icebergBlocks.push(icebergLines.join("\n"));

    // Load statements.
    if (table.partitionColumns.length > 0) {
      loadLines.push(`MSCK REPAIR TABLE ${athenaIdent(`${db}_raw`)}.${athenaIdent(name)};`);
    }
    const selectColumns = [...regular, ...partitionColumns].map((column) =>
      column.isChar ? `CAST(${sqlIdent(column.name)} AS varchar)` : sqlIdent(column.name),
    );
    loadLines.push(
      `INSERT INTO ${sqlIdent(db)}.${sqlIdent(name)} SELECT ${selectColumns.join(", ")} FROM ${sqlIdent(`${db}_raw`)}.${sqlIdent(name)};`,
    );
  }
  files.set("sql/target/02-raw-tables.sql", joinBlocks(rawBlocks));
  files.set("sql/target/03-iceberg-tables.sql", joinBlocks(icebergBlocks));

  const viewsByDb = new Map<string, ViewDef[]>();
  for (const view of sourceOrdered(project.views)) {
    const db = view.schema.toLowerCase();
    const list = viewsByDb.get(db) ?? [];
    list.push(view);
    viewsByDb.set(db, list);
  }
  for (const db of [...viewsByDb.keys()].sort((a, b) => a.localeCompare(b))) {
    const views = viewsByDb.get(db) ?? [];
    files.set(
      `sql/target/04-views-${db}.sql`,
      joinBlocks(views.map((view) => viewBlock(project.engine, view, "double", false))),
    );
  }

  files.set("sql/load/load.sql", joinBlocks(loadLines));

  return {
    files,
    warnings,
    ...(datasyncPaths.length > 0
      ? {
          datasync: {
            root,
            ...(includeFilter !== "" ? { includeFilter } : {}),
          },
        }
      : {}),
    externalS3Buckets: [...externalS3Buckets].sort((a, b) => a.localeCompare(b)),
  };
}

export function generateTargetDdl(project: DatabaseProject): GeneratedTargetDdl {
  switch (project.engine) {
    case "oracle":
    case "sqlserver":
      return generateAuroraPostgresqlFromSources(project);
    case "postgresql":
      return generatePostgresqlHomogeneous(project);
    case "mysql":
      return generateAuroraMysql(project);
    case "teradata":
    case "netezza":
      return generateRedshift(project);
    case "hive":
      return generateAthenaIceberg(project);
  }
}
