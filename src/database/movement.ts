// --- DMS (database class) --------------------------------------------------------

export interface DmsRule {
  "rule-type": "selection" | "transformation";
  "rule-id": string;
  "rule-name": string;
  "rule-target"?: string;
  "object-locator": Record<string, string>;
  "rule-action": string;
}

export function buildDmsTableMappings(project: DatabaseProject): { rules: DmsRule[] } {
  const rules: DmsRule[] = [];
  let id = 1;
  const schemas = [...new Set(project.tables.map((table) => table.schema))].sort((a, b) =>
    a.localeCompare(b),
  );
  for (const schema of schemas) {
    rules.push({
      "rule-type": "selection",
      "rule-id": String(id++),
      "rule-name": `include-${schema}`,
      "object-locator": { "schema-name": schema, "table-name": "%" },
      "rule-action": "include",
    });
  }
  if (project.engine === "oracle" || project.engine === "sqlserver") {
    const transformation = (
      name: string,
      target: string,
      locator: Record<string, string>,
    ): DmsRule => ({
      "rule-type": "transformation",
      "rule-id": String(id++),
      "rule-name": name,
      "rule-target": target,
      "object-locator": locator,
      "rule-action": "convert-lowercase",
    });
    rules.push(transformation("lowercase-schemas", "schema", { "schema-name": "%" }));
    rules.push(
      transformation("lowercase-tables", "table", { "schema-name": "%", "table-name": "%" }),
    );
    rules.push(
      transformation("lowercase-columns", "column", { "schema-name": "%", "column-name": "%" }),
    );
  }
  return { rules };
}

