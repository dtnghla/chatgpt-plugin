// --- Teradata export --------------------------------------------------------------

const TPT_JOB_TEMPLATE = [
  "DEFINE JOB export_table",
  "DESCRIPTION 'Export one table to a pipe-delimited file. Generated by aws-data-modernizer; review before running.'",
  "(",
  "  APPLY TO OPERATOR ($FILE_WRITER()",
  "    ATTR (DirectoryPath = @OutputDirectory, FileName = @TargetFile, Format = 'Delimited', TextDelimiter = '|', QuotedData = 'Optional', OpenQuoteMark = '\"', CloseQuoteMark = '\"'))",
  "  SELECT * FROM OPERATOR ($EXPORT()",
  "    ATTR (TdpId = @TdpId, UserName = @UserName, UserPassword = @UserPassword, SelectStmt = @SelectStmt));",
  ");",
].join("\n");

function numericParam(params: string[]): number | null {
  const raw = params[0];
  if (raw === undefined) return null;
  const parsed = Number.parseInt(raw, 10);
  return Number.isNaN(parsed) ? null : parsed;
}

function teradataCast(column: ColumnDef): string {
  const parts = parseSourceType(column.sourceType);
  const base = parts.base;
  const name = column.name;
  const p = numericParam(parts.params);
  if (base === "CHAR" || base === "VARCHAR") {
    return `CAST(${name} AS VARCHAR(${p ?? 64000}))`;
  }
  if (base === "BYTEINT" || base === "SMALLINT" || base === "INTEGER" || base === "BIGINT") {
    return `CAST(${name} AS VARCHAR(20))`;
  }
  if (base === "DECIMAL" || base === "NUMERIC" || base === "NUMBER") {
    return `CAST(${name} AS VARCHAR(42))`;
  }
  if (base === "FLOAT" || base === "REAL" || base === "DOUBLE" || base === "DOUBLE PRECISION") {
    return `CAST(${name} AS VARCHAR(30))`;
  }
  if (base === "DATE") {
    return `CAST(CAST(${name} AS FORMAT 'YYYY-MM-DD') AS VARCHAR(10))`;
  }
  if (base === "TIME") {
    return `CAST(${name} AS VARCHAR(21))`;
  }
  if (base === "TIMESTAMP") {
    const format = p === 0 ? "YYYY-MM-DDBHH:MI:SS" : `YYYY-MM-DDBHH:MI:SS.S(${p ?? 6})`;
    return `CAST(CAST(${name} AS FORMAT '${format}') AS VARCHAR(32))`;
  }
  if (base.startsWith("INTERVAL")) {
    return `CAST(${name} AS VARCHAR(32))`;
  }
  if (base === "LONG" || base === "LONG VARCHAR") {
    return `CAST(${name} AS VARCHAR(64000))`;
  }
  return `CAST(${name} AS VARCHAR(64000))`;
}

function tptEscape(text: string): string {
  return text.replaceAll("'", "''");
}

function bashDoubleEscape(text: string): string {
  return text
    .replaceAll("\\", "\\\\")
    .replaceAll('"', '\\"')
    .replaceAll("$", "\\$")
    .replaceAll("`", "\\`");
}

export function generateTeradataExport(project: DatabaseProject): Map<string, string> {
  const files = new Map<string, string>();
  files.set("export/teradata-export.tpt", `${TPT_JOB_TEMPLATE}\n`);
  const lines = [
    "#!/usr/bin/env bash",
    "set -euo pipefail",
    "",
    "# Generated by aws-data-modernizer. Exports the COPY tables to pipe-delimited files.",
    "# Credentials are read from the environment only and are never written to disk.",
    "",
    ': "${TD_TDPID:?Set TD_TDPID in the environment}"',
    ': "${TD_USER:?Set TD_USER in the environment}"',
    ': "${TD_PASSWORD:?Set TD_PASSWORD in the environment}"',
    ': "${EXPORT_DIR:?Set EXPORT_DIR in the environment}"',
    "",
  ];
  const tables = project.tables.filter(
    (table) => decideTableMovement(project, table).movement === "copy",
  );
  for (const table of tables) {
    const schema = table.schema.toLowerCase();
    const name = table.name.toLowerCase();
    const select = `SELECT ${table.columns.map(teradataCast).join(", ")} FROM ${table.schema}.${table.name};`;
    const argument = bashDoubleEscape(tptEscape(select));
    lines.push(`mkdir -p "$EXPORT_DIR/${schema}/${name}"`);
    lines.push(
      `tbuild -f "$(dirname "$0")/teradata-export.tpt" -u "TdpId='$TD_TDPID', UserName='$TD_USER', UserPassword='$TD_PASSWORD', OutputDirectory='$EXPORT_DIR/${schema}/${name}/', TargetFile='${name}.psv', SelectStmt='${argument}'" "export_${schema}_${name}"`,
    );
    lines.push("");
  }
  files.set("export/export-teradata.sh", `${lines.join("\n")}\n`);
  return files;
}

// --- Netezza export ---------------------------------------------------------------

export function generateNetezzaExport(project: DatabaseProject): Map<string, string> {
  const sqlLines: string[] = [];
  const shellLines = [
    "#!/usr/bin/env bash",
    "set -euo pipefail",
    "",
    "# Generated by aws-data-modernizer. Exports the COPY tables with Netezza external tables.",
    "# NZ_PASSWORD is read by nzsql from the environment; EXPORT_DIR is a path on the Netezza host.",
    "",
    ': "${NZ_HOST:?Set NZ_HOST in the environment}"',
    ': "${NZ_DATABASE:?Set NZ_DATABASE in the environment}"',
    ': "${NZ_USER:?Set NZ_USER in the environment}"',
    ': "${NZ_PASSWORD:?Set NZ_PASSWORD in the environment}"',
    ': "${EXPORT_DIR:?Set EXPORT_DIR in the environment}"',
    "",
  ];
  const tables = project.tables.filter(
    (table) => decideTableMovement(project, table).movement === "copy",
  );
  for (const table of tables) {
    const schema = table.schema.toLowerCase();
    const name = table.name.toLowerCase();
    sqlLines.push(
      `CREATE EXTERNAL TABLE '__EXPORT_DIR__/${schema}/${name}/${name}.psv' USING (DELIMITER '|' QUOTEDVALUE 'DOUBLE' NULLVALUE '') AS SELECT * FROM ${table.schema}.${table.name};`,
    );
    shellLines.push(`mkdir -p "$EXPORT_DIR/${schema}/${name}"`);
  }
  shellLines.push(
    `sed "s#__EXPORT_DIR__#$EXPORT_DIR#g" "$(dirname "$0")/export-netezza.sql" | nzsql -host "$NZ_HOST" -d "$NZ_DATABASE" -u "$NZ_USER"`,
  );
  const files = new Map<string, string>();
  files.set("export/export-netezza.sql", `${sqlLines.join("\n")}\n`);
  files.set("export/export-netezza.sh", `${shellLines.join("\n")}\n`);
  return files;
}

// --- SQL apply plan (warehouse and lake) -------------------------------------------

export interface ApplyPlanEntry {
  path: string;
  continue_on_error: boolean;
  database?: string;
}

export interface ApplyPlan {
  plan_format: 1;
  target: "redshift-serverless" | "athena-iceberg";
  phases: { schema: ApplyPlanEntry[]; load: ApplyPlanEntry[] };
}

export function buildWarehouseApplyPlan(): ApplyPlan {
  return {
    plan_format: 1,
    target: "redshift-serverless",
    phases: {
      schema: [
        { path: "sql/target/01-schemas.sql", continue_on_error: false },
        { path: "sql/target/02-tables.sql", continue_on_error: false },
        { path: "sql/target/03-views.sql", continue_on_error: true },
      ],
      load: [{ path: "sql/load/copy.sql", continue_on_error: false }],
    },
  };
}

export function buildLakeApplyPlan(viewFiles: { path: string; database: string }[]): ApplyPlan {
  return {
    plan_format: 1,
    target: "athena-iceberg",
    phases: {
      schema: [
        { path: "sql/target/01-databases.sql", continue_on_error: false },
        { path: "sql/target/02-raw-tables.sql", continue_on_error: false },
        { path: "sql/target/03-iceberg-tables.sql", continue_on_error: true },
        ...viewFiles.map((view) => ({
          path: view.path,
          continue_on_error: true,
          database: view.database,
        })),
      ],
      load: [{ path: "sql/load/load.sql", continue_on_error: false }],
    },
  };
}
