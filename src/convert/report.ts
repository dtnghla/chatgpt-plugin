import type {
  BundleFile,
  ConnectionSummary,
  GlueJobArtifact,
  ProjectAssessment,
  ScheduleSummary,
  StateMachineArtifact,
} from "../migration/types.js";

export interface ReportFile {
  path: string;
  kind: BundleFile["kind"];
  bytes?: number;
}

export interface SqlRunnerReport {
  name: string;
  scriptPath: string;
  entries: number;
  warnings: string[];
}

export interface ReportContext {
  projectName: string;
  generatedWith: string;
  assessment: ProjectAssessment;
  jobs: GlueJobArtifact[];
  stateMachines: StateMachineArtifact[];
  connections: ConnectionSummary[];
  schedules: ScheduleSummary[];
  files: ReportFile[];
  sqlRunner?: SqlRunnerReport;
  warnings: string[];
}

export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

function cell(value: string | number | boolean | undefined): string {
  return String(value ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\r?\n/g, " ");
}

function table(headers: string[], rows: (string | number | boolean | undefined)[][]): string {
  const header = `| ${headers.map(cell).join(" | ")} |`;
  const divider = `| ${headers.map(() => "---").join(" | ")} |`;
  return [header, divider, ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`)].join("\n");
}

export function bundleNextSteps(context: ReportContext): string[] {
  const steps: string[] = [];
  const manual = context.assessment.unsupportedSteps.length;
  if (manual > 0) {
    steps.push(
      `Rewrite the ${manual} manual step${manual === 1 ? "" : "s"} listed in migration-report.md, or regenerate with step_overrides for each one.`,
    );
  }
  const placeholders = context.connections.filter((connection) =>
    connection.jdbcUrl.includes("REPLACE_ME"),
  );
  if (placeholders.length > 0) {
    steps.push(
      `Resolve the placeholder endpoint${placeholders.length === 1 ? "" : "s"} for ${placeholders.map((connection) => connection.name).join(", ")} before deploying.`,
    );
  }
  if (context.connections.length > 0) {
    steps.push(
      "After creating the stack, replace the placeholder username, password and URL in each generated Secrets Manager secret.",
    );
  }
  if (context.schedules.length > 0) {
    steps.push(
      "Confirm that the generated EventBridge Scheduler expressions should run in UTC (PDI did not store a time zone).",
    );
  }
  steps.push(
    "Review the IAM policies, Glue worker sizing and the generated PySpark scripts before running anything in AWS.",
    "Upload the glue/scripts folder to the scripts bucket, then deploy cloudformation/pentaho-migration.yaml with the AWS CLI.",
  );
  return steps;
}

export function buildMigrationReport(context: ReportContext): string {
  const { assessment } = context;
  const lines: string[] = [];
  lines.push(`# ${context.projectName}: Pentaho to AWS migration report`);
  lines.push("");
  lines.push(
    `Generated by ${context.generatedWith}. This report was produced from the uploaded Pentaho files only; the generator did not contact AWS and did not read any Pentaho server or database.`,
  );
  lines.push("");
  lines.push(
    `**Readiness:** ${assessment.readiness.score}/100 (${assessment.readiness.level}). ${assessment.readiness.summary}`,
  );
  if (assessment.readiness.blockers.length > 0) {
    lines.push("");
    lines.push("**Blockers:**");
    for (const blocker of assessment.readiness.blockers) lines.push(`- ${blocker}`);
  }
  lines.push("");
  lines.push("## Inventory");
  lines.push("");
  lines.push(
    table(
      ["File", "Kind", "Size", "SHA-256"],
      assessment.files.map((file) => [
        file.path,
        file.kind,
        formatBytes(file.bytes),
        file.sha256.slice(0, 16),
      ]),
    ),
  );
  lines.push("");
  lines.push("## Generated artifacts");
  lines.push("");
  lines.push(
    table(
      ["Path", "Kind", "Size"],
      context.files.map((file) => [
        file.path,
        file.kind,
        file.bytes === undefined ? "included" : formatBytes(file.bytes),
      ]),
    ),
  );
  lines.push("");
  lines.push("## Glue jobs");
  lines.push("");
  if (context.jobs.length === 0) {
    lines.push("No Glue jobs were generated.");
  } else {
    lines.push(
      table(
        ["Transformation", "Glue job", "Script", "Automatic", "Partial", "Manual"],
        context.jobs.map((job) => [
          job.transformation,
          job.glueJobName,
          job.scriptPath,
          job.automaticSteps.length,
          job.partialSteps.length,
          job.manualSteps.length,
        ]),
      ),
    );
    lines.push("");
    for (const job of context.jobs) {
      if (job.manualSteps.length === 0 && job.warnings.length === 0) continue;
      lines.push(`### ${job.transformation}`);
      lines.push("");
      if (job.manualSteps.length > 0) {
        lines.push(`Manual steps: ${job.manualSteps.join(", ")}.`);
      }
      for (const warning of job.warnings) lines.push(`- ${warning}`);
      lines.push("");
    }
  }
  if (context.sqlRunner) {
    lines.push("### SQL runner");
    lines.push("");
    lines.push(
      `The SQL-runner Glue job \`${context.sqlRunner.name}\` executes ${context.sqlRunner.entries} SQL job entr${context.sqlRunner.entries === 1 ? "y" : "ies"}; its script is \`${context.sqlRunner.scriptPath}\`.`,
    );
    for (const warning of context.sqlRunner.warnings) lines.push(`- ${warning}`);
    lines.push("");
  }
  lines.push("## Step Functions state machines");
  lines.push("");
  if (context.stateMachines.length === 0) {
    lines.push("No jobs were uploaded, so no state machines were generated.");
  } else {
    lines.push(
      table(
        ["PDI job", "State machine", "Definition", "Schedules"],
        context.stateMachines.map((machine) => [
          machine.job,
          machine.stateMachineName,
          machine.definitionPath,
          machine.scheduleCount,
        ]),
      ),
    );
    lines.push("");
    for (const machine of context.stateMachines) {
      if (machine.warnings.length === 0) continue;
      lines.push(`### ${machine.job}`);
      for (const warning of machine.warnings) lines.push(`- ${warning}`);
      lines.push("");
    }
  }
  lines.push("## Connections");
  lines.push("");
  if (context.connections.length === 0) {
    lines.push("No database connections were found.");
  } else {
    lines.push(
      table(
        ["Name", "Type", "JDBC URL", "Secret name", "Password in source"],
        context.connections.map((connection) => [
          connection.name,
          connection.type,
          connection.jdbcUrl,
          connection.secretName,
          connection.hasPassword ? "yes (removed)" : "no",
        ]),
      ),
    );
    lines.push("");
    for (const connection of context.connections) {
      for (const warning of connection.warnings) lines.push(`- ${connection.name}: ${warning}`);
    }
    if (context.connections.some((connection) => connection.warnings.length > 0)) lines.push("");
  }
  lines.push("## Schedules");
  lines.push("");
  if (context.schedules.length === 0) {
    lines.push("No PDI scheduler entries were found.");
  } else {
    lines.push(
      table(
        ["Job", "Entry", "Mapped", "Expression", "Description"],
        context.schedules.map((schedule) => [
          schedule.job,
          schedule.entry,
          schedule.mapped ? "yes" : "no",
          schedule.expression ?? "",
          schedule.description,
        ]),
      ),
    );
    lines.push("");
  }
  lines.push("## Step mapping coverage");
  lines.push("");
  lines.push(
    table(
      ["PDI step type", "Count", "Status", "Conversion", "Caveat"],
      assessment.stepCoverage.map((coverage) => [
        coverage.type,
        coverage.count,
        coverage.status,
        coverage.conversion,
        coverage.caveat ?? "",
      ]),
    ),
  );
  if (assessment.jobEntryCoverage.length > 0) {
    lines.push("");
    lines.push("## Job entry coverage");
    lines.push("");
    lines.push(
      table(
        ["PDI entry type", "Count", "Status", "Conversion"],
        assessment.jobEntryCoverage.map((coverage) => [
          coverage.type,
          coverage.count,
          coverage.status,
          coverage.conversion,
        ]),
      ),
    );
  }
  lines.push("");
  lines.push("## Parameters and variables");
  lines.push("");
  if (assessment.parameters.length === 0 && assessment.variables.length === 0) {
    lines.push("No parameters or variables were found.");
  } else {
    if (assessment.parameters.length > 0) {
      lines.push(
        table(
          ["Parameter", "Default", "Description", "Files"],
          assessment.parameters.map((parameter) => [
            parameter.name,
            parameter.defaultValue ?? "",
            parameter.description ?? "",
            parameter.files.join(", "),
          ]),
        ),
      );
      lines.push("");
    }
    if (assessment.variables.length > 0) {
      lines.push(`Variables referenced in the files: ${assessment.variables.join(", ")}.`);
      lines.push("");
    }
  }
  lines.push("## Dependencies");
  lines.push("");
  if (assessment.dependencies.length === 0) {
    lines.push("No transformation or nested-job references were found.");
  } else {
    lines.push(
      table(
        ["From file", "Entry", "Kind", "Target", "Resolved"],
        assessment.dependencies.map((dependency) => [
          dependency.fromFile,
          dependency.entry,
          dependency.kind,
          dependency.target,
          dependency.resolved ? "yes" : "no",
        ]),
      ),
    );
  }
  lines.push("");
  lines.push("## Risks");
  lines.push("");
  if (assessment.risks.length === 0) {
    lines.push("No risks were recorded.");
  } else {
    lines.push(
      table(
        ["Severity", "Code", "Message", "File"],
        assessment.risks.map((risk) => [risk.severity, risk.code, risk.message, risk.file ?? ""]),
      ),
    );
  }
  if (context.warnings.length > 0) {
    lines.push("");
    lines.push("## Generation warnings");
    lines.push("");
    for (const warning of context.warnings) lines.push(`- ${warning}`);
  }
  lines.push("");
  lines.push("## Open questions");
  lines.push("");
  if (assessment.questions.length === 0) {
    lines.push("No open questions were recorded.");
  } else {
    for (const question of assessment.questions) lines.push(`- ${question}`);
  }
  lines.push("");
  lines.push("## Next steps");
  lines.push("");
  for (const step of bundleNextSteps(context)) lines.push(`- ${step}`);
  lines.push("");
  lines.push(
    "The generated bundle is a starting point, not a proof of equivalence. Validate row counts, data types and business rules against the source system before cut-over.",
  );
  lines.push("");
  return lines.join("\n");
}

export function buildBundleReadme(context: ReportContext, scriptPrefix: string): string {
  const topics: string[] = [];
  if (context.stateMachines.some((machine) => machine.entryTypes.includes("MAIL"))) {
    topics.push("SNS notifications for PDI MAIL entries");
  }
  const hasSchedules = context.schedules.some((schedule) => schedule.mapped);
  const lines: string[] = [];
  lines.push(`# ${context.projectName} AWS migration bundle`);
  lines.push("");
  lines.push(`Generated by ${context.generatedWith} from Pentaho Data Integration files.`);
  lines.push("");
  lines.push(
    "This bundle is deployable infrastructure-as-code, but it is generated advice rather than a validated migration. The generator never contacted AWS and holds no credentials.",
  );
  lines.push("");
  lines.push("## Contents");
  lines.push("");
  lines.push("```text");
  for (const file of context.files) {
    lines.push(file.bytes === undefined ? file.path : `${file.path}  (${formatBytes(file.bytes)})`);
  }
  lines.push("```");
  lines.push("");
  lines.push("## Before you deploy");
  lines.push("");
  lines.push(
    "1. Read `migration-report.md`, especially the readiness block, risks and open questions.",
  );
  lines.push(
    `2. Upload the contents of \`${scriptPrefix}/\` to an S3 scripts bucket, preserving the folder layout.`,
  );
  lines.push("3. Create or choose an S3 data bucket for the migrated files.");
  if (context.connections.length > 0) {
    lines.push(
      "4. Review each JDBC URL in `cloudformation/pentaho-migration.yaml`; values containing `REPLACE_ME` must be fixed.",
    );
  }
  if (topics.length > 0) {
    lines.push(`5. Configure subscriptions for ${topics.join(", ")}.`);
  }
  lines.push("");
  lines.push("## Deploy with the AWS CLI");
  lines.push("");
  lines.push("```bash");
  lines.push('AWS_REGION="us-east-1"');
  lines.push('STACK_NAME="' + context.projectName + '"');
  lines.push('SCRIPTS_BUCKET="my-scripts-bucket"');
  lines.push('DATA_BUCKET="my-data-bucket"');
  lines.push("");
  lines.push(`aws s3 cp --recursive ${scriptPrefix}/ "s3://$SCRIPTS_BUCKET/${scriptPrefix}/"`);
  lines.push("");
  lines.push("aws cloudformation deploy \\");
  lines.push('  --region "$AWS_REGION" \\');
  lines.push('  --stack-name "$STACK_NAME" \\');
  lines.push("  --template-file cloudformation/pentaho-migration.yaml \\");
  lines.push("  --capabilities CAPABILITY_IAM \\");
  lines.push('  --parameter-overrides "DataBucket=$DATA_BUCKET" "ScriptsBucket=$SCRIPTS_BUCKET"');
  lines.push("```");
  lines.push("");
  if (context.connections.length > 0) {
    lines.push("After the stack is created, replace every placeholder secret value:");
    lines.push("");
    lines.push("```bash");
    lines.push(
      'aws secretsmanager put-secret-value --secret-id "' +
        context.projectName +
        '/<SECRET_NAME>" --secret-string \'{"username":"<USER>","password":"<PASSWORD>","url":"<JDBC_URL>"}\'',
    );
    lines.push("```");
    lines.push("");
    lines.push(
      "The secret names are listed in `migration-report.md`. Never commit real credentials to this bundle.",
    );
    lines.push("");
  }
  const first = context.stateMachines[0];
  if (first) {
    lines.push("Start a migrated job manually with Step Functions:");
    lines.push("");
    lines.push("```bash");
    lines.push(`aws stepfunctions start-execution --state-machine-arn "<ARN>" --input '{}'`);
    lines.push("```");
    lines.push("");
    lines.push(
      `State machine ARNs are printed as CloudFormation outputs. The first one runs \`${first.job}\` (\`${first.stateMachineName}\`).`,
    );
    lines.push("");
  }
  if (hasSchedules) {
    lines.push("## Schedules");
    lines.push("");
    lines.push(
      "PDI did not store a time zone with its schedules. The generated EventBridge Scheduler expressions run in UTC; adjust them if the original jobs ran in another time zone.",
    );
    lines.push("");
  }
  lines.push("## Limitations");
  lines.push("");
  lines.push(
    "- Manual steps are emitted as stubs or Pass states and must be rewritten before the job produces correct output.",
  );
  lines.push(
    "- The Glue scripts assume the source files can be read from S3. Local paths are mapped with the supplied path mappings; unmatched paths go to `s3://<DataBucket>/unmapped/`.",
  );
  lines.push(
    "- The generated state machines linearize PDI job graphs, so parallel branches that rely on shared state are not reproduced.",
  );
  lines.push(
    "- Job-level data semantics, such as partition pruning, slow-changing dimensions and transaction boundaries, need review against the source system.",
  );
  lines.push("");
  return lines.join("\n");
}
